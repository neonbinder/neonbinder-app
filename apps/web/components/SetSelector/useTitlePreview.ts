import { useQuery } from "convex/react";
import { api } from "../../convex/_generated/api";
import type { Id } from "../../convex/_generated/dataModel";
// Pure and browser-safe: the same generator the server titled the card with.
import { assessListingTitle, leftOutOfTitle } from "../../convex/features/generateListing";
import { variantTypeKindFromTitle } from "../../convex/variantRole";

/**
 * NEO-101 — "Regenerate", and the source fields behind a generated title.
 *
 * ## Why the title needs a rebuild button at all
 *
 * `listingTitle` is written ONCE, at card creation, and never regenerated by a
 * sync (NEO-24/NEO-25's write-once rule — a re-sync must never stomp an
 * operator's wording). That rule is right, and it has one cost: a card whose
 * player, set or variation was corrected AFTER creation keeps a title built
 * from the old facts, and nothing in the product will ever fix it. This is the
 * one deliberate escape hatch, driven by the operator, one card at a time.
 *
 * ## Why the source chips ship with it
 *
 * The generator drops optional tokens until the title fits, so a title at the
 * cap is a title with something MISSING, and the missing thing is invisible in
 * the field. Rendering the inputs the title was built from turns "shorten this"
 * from a guessing game into an edit: the operator can see that "Image
 * Variation; Wearing sunglasses" is what pushed it over, and shorten THAT
 * rather than hacking at the player's name. The chips are plain text and never
 * links — a card's variation text is operator- and marketplace-sourced content,
 * not a destination.
 *
 * ## Subscribed from the start (NEO-535)
 *
 * The query used to stay `"skip"` until the operator pressed Regenerate, so
 * "Left out to fit" and the chips appeared only after a press, on a title that
 * was already stored. They are read from the card's facts, which only the
 * server holds, so the hook now subscribes as it mounts: one small query per
 * opened card (the card, its chain, its players and teams), and Regenerate
 * itself is instant because its answer is already here.
 */

/** One labelled source fact, e.g. `Set` → `Topps Chrome`. */
export type TitleSourceChip = { label: string; value: string };

type PreviewResult = {
  title: string;
  /** NEO-535 — optional: an older deploy predates them. */
  fits?: boolean;
  firstNameLost?: boolean;
  shortNameUsed?: boolean;
  coreFits: boolean;
  dropped: string[];
  inputs: {
    cardNumber: string;
    playerNames: string[];
    year?: string;
    manufacturer?: string;
    /**
     * NEO-272 — true when NB has not identified this set's brand: the set hangs
     * off the marketplace's all-brands FILTER OPTION ("show all cards from all
     * brands"), which the set sync files a set under when it cannot match it to
     * a real manufacturer. That name says nothing about the card, so the
     * generator spends no title characters on it — `manufacturer` above is
     * present but was not used.
     *
     * An NB role flag resolved server-side, never a name comparison: the name
     * is a marketplace filter label NB does not own, and it decides nothing
     * here or anywhere (CLAUDE.md, product invariant 4). Declared OPTIONAL for
     * the same reason as `teamNames` below: a browser holding this bundle can
     * be reading an older deploy that predates the field. `undefined` therefore
     * has to mean "the brand is known", which is exactly what every preview
     * from such a deploy is.
     */
    manufacturerBrandUnknown?: boolean;
    setName?: string;
    /**
     * NEO-335 — the insert's name (gated on its NB role server-side) and the
     * set's short name for titles. Optional: an older deploy predates them.
     */
    insertName?: string;
    setShortName?: string;
    parallelName?: string;
    /** NEO-335 — the leaf's parallel ROLE (earns the "Parallel" label). */
    parallelIsRole?: boolean;
    isRookie?: boolean;
    isRelic?: boolean;
    autographed?: string;
    shortPrint?: string;
    printRun?: number;
    cardVariation?: string;
    /**
     * Stored team names, verbatim. Declared OPTIONAL although the query always
     * returns it (possibly empty): a browser holding this bundle can be reading
     * an older deploy that predates the field, and a `.map` on `undefined`
     * inside a modal dialog takes the whole dialog with it.
     */
    teamNames?: string[];
    /**
     * NEO-606 — the Location / Name of those teams that have one. The title
     * gives a team's location up before the team, and `leftOutOfTitle` reads
     * the same split, so the note and the title agree. Optional: an older
     * deploy predates it, and without it a team is only ever dropped whole.
     */
    teamSplits?: Array<{ location: string; name: string }>;
    /** e.g. "Baseball". Optional for the same reason, and genuinely absent for
     * a set whose sport was never resolved. */
    sport?: string;
  };
};

/**
 * Format one input as a chip value, or drop it.
 *
 * Takes `unknown` on purpose: the flag fields on `ListingCardInputs` are a mix
 * of booleans and strings, and this module must not go stale when one of them
 * changes shape server-side. `true` renders the label itself (a boolean
 * `isRookie` becomes the chip `RC`), which is also how the generator words it.
 */
function chipValue(value: unknown, whenTrue: string): string | null {
  if (value == null || value === false || value === "") return null;
  if (value === true) return whenTrue;
  if (typeof value === "number") return String(value);
  if (typeof value === "string") return value;
  return null;
}

/** NEO-535 — a feature value that says the card has no such thing. */
const noValue = (value: string | undefined): boolean =>
  !value?.trim() || value.trim() === "None";

/**
 * The chips for a preview, in the order the generator itself lays a title
 * down (NEO-535): the set description (year, maker, set, insert, parallel —
 * or the "Set name in titles" box that stood in for all of it), players,
 * number, then AUTO, RELIC, the print run, the variation, RC, SP/SSP, teams
 * and sport.
 *
 * Reading the row left to right therefore reads the title left to right.
 */
export function titleSourceChips(inputs: PreviewResult["inputs"]): TitleSourceChip[] {
  const chips: TitleSourceChip[] = [];
  const push = (label: string, value: unknown, whenTrue = label) => {
    const v = chipValue(value, whenTrue);
    if (v !== null) chips.push({ label, value: v });
  };

  // NEO-335/535 — the set description, or the box text that stood in for all
  // of it. Which one the title used is the generator's answer for these same
  // inputs (`shortNameUsed`), never a guess from the title text.
  const shortNameUsed =
    !!inputs.setShortName?.trim() && assessListingTitle(inputs).shortNameUsed === true;
  if (shortNameUsed) {
    push("Set name in titles", inputs.setShortName);
  } else {
    pushDescription(push, inputs);
  }
  // One chip per player, not a joined string: on a multi-player card the names
  // are what an operator weighs against each other when shortening.
  for (const name of inputs.playerNames ?? []) {
    if (name) chips.push({ label: "Player", value: name });
  }
  if (inputs.cardNumber) chips.push({ label: "Number", value: `#${inputs.cardNumber}` });

  // Then the card's own tokens, in the order the title says them.
  // NEO-535 — "None" is the features' word for "not an autograph" / "not a
  // short print": no chip, as for any other absent fact.
  if (!noValue(inputs.autographed)) push("Auto", inputs.autographed, "AUTO");
  push("Relic", inputs.isRelic, "RELIC");
  if (inputs.printRun != null) chips.push({ label: "Print run", value: `/${inputs.printRun}` });
  push("Variation", inputs.cardVariation);
  push("Rookie", inputs.isRookie, "RC");
  if (!noValue(inputs.shortPrint)) push("Short print", inputs.shortPrint, "SP");
  // One chip per team, matching the per-player treatment: a card can carry
  // two, and "which of these is worth the characters" is the same judgement.
  for (const name of inputs.teamNames ?? []) {
    if (name) chips.push({ label: "Team", value: name });
  }
  push("Sport", inputs.sport);

  return chips;
}

/** The builder's own description chips: year, maker, set, insert, parallel. */
function pushDescription(
  push: (label: string, value: unknown, whenTrue?: string) => void,
  inputs: PreviewResult["inputs"],
): void {
  push("Year", inputs.year);
  // NEO-272: a set whose brand NB has not identified gets NO Maker chip. The
  // generator leaves that manufacturer out of the title, so a chip naming it
  // states a fact the title does not contain — and this row exists so an
  // operator who has to shorten a title can see which characters are in play.
  // A chip for a maker that cost zero characters sends them hunting for
  // characters nobody spent.
  //
  // Suppressed rather than rendered in a visibly-unused state, deliberately:
  // the row is read left to right BECAUSE that mirrors the title (see above),
  // and a chip that is not in the title breaks that mapping wherever it sits —
  // so the honest "unused" rendering would need a second visual language on a
  // dialog NEO-271 already calls too small, to tell the operator about a fact
  // whose only useful content is that it is not there.
  //
  // Keyed on the flag, never on the manufacturer's name.
  if (!inputs.manufacturerBrandUnknown) push("Maker", inputs.manufacturer);
  push("Set", inputs.setName);
  push("Insert", inputs.insertName);
  // NEO-535 — "Base" names no parallel (the Base kind's word, read through the
  // role helper, never a literal), so a base card shows no Parallel chip.
  const parallel = inputs.parallelName?.trim();
  if (parallel && variantTypeKindFromTitle(parallel) !== "base") push("Parallel", parallel);
}

export type TitlePreview = {
  /** The source facts behind the last preview. Empty until one is fetched. */
  chips: TitleSourceChip[];
  /**
   * NEO-535 — "Left out to fit" for `text`, the title as it reads in the field
   * NOW (the operator's own words included), from the card's facts. Empty
   * until a preview is fetched; never the generator's own assessment, so
   * retyping a cut word takes it off the note.
   */
  leftOutOf: (text: string) => string[];
  /** A regenerate is in flight (or its query has not resolved yet). */
  loading: boolean;
  /**
   * A regenerate was asked for over a dirty draft and is waiting for a second
   * click. Surfaces as a confirm line, never a `window.confirm` — a browser
   * dialog steals focus out of the drawer and cannot be styled or tested.
   */
  confirming: boolean;
  /** Ask for a fresh title. Pass whether the draft has unsaved edits. */
  request: (dirty: boolean) => void;
  /** Drop a pending confirm — call it when the operator edits the draft again. */
  cancelConfirm: () => void;
};

/**
 * @param cardId the card to preview a title for
 * @param applyTitle where a fetched title lands. Pass a `useState` setter: it
 *   is a dependency of the apply effect, so an inline arrow would re-run it.
 */
export function useTitlePreview(
  cardId: Id<"cardChecklist">,
  applyTitle: (title: string) => void,
): TitlePreview {
  const [pending, setPending] = useState(false);
  const [confirming, setConfirming] = useState(false);

  // Typed by annotation rather than a cast: the generated return type has to be
  // assignable to `PreviewResult`, so a backend field that changes shape breaks
  // this line instead of quietly rendering nothing.
  const preview: PreviewResult | undefined = useQuery(
    api.selectorOptions.previewListingTitle,
    { cardId },
  );

  useEffect(() => {
    if (!pending || preview === undefined) return;
    applyTitle(preview.title);
    // Reacting to a server response landing, not deriving render state — the
    // query is async and there is no render in which both "asked" and "has an
    // answer" are known without this.
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setPending(false);
  }, [pending, preview, applyTitle]);

  const request = useCallback(
    (dirty: boolean) => {
      // A dirty draft is the operator's own wording. Replacing it is a real
      // loss, so it costs a second, deliberate click.
      if (dirty && !confirming) {
        setConfirming(true);
        return;
      }
      setConfirming(false);
      setPending(true);
    },
    [confirming],
  );

  const cancelConfirm = useCallback(() => setConfirming(false), []);

  // `preview?.inputs` rather than `preview`: this hook renders inside a modal
  // dialog, and a response missing its `inputs` (a bundle reading an older
  // deploy's return shape) must show no chips, not throw the dialog away.
  const chips = useMemo(
    () => (preview?.inputs ? titleSourceChips(preview.inputs) : []),
    [preview],
  );

  const inputs = preview?.inputs;
  const leftOutOf = useCallback(
    (text: string) => (inputs ? leftOutOfTitle(inputs, text.trim()) : []),
    [inputs],
  );

  return {
    chips,
    leftOutOf,
    loading: pending,
    confirming,
    request,
    cancelConfirm,
  };
}
