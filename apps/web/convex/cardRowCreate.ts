/**
 * NB-owned fields a COPY carries verbatim from the card it copies (NEO-312).
 * The commit passes only the team bookkeeping, and only when the card earned
 * it before save (NEO-335, `settleCardTeamAnswer` in selectorOptions.ts):
 * `teamCheckDoneAt` (+ `teamCheckOutcome`, NEO-345, and `bscTeamName`) for a
 * card whose fetch-time BSC lookup answered, or `teamNoneConfirmedAt` / `teamNoneConfirmedByUserId` for an
 * operator's "No team on this card". It never passes a variation link.
 */
export type CarriedCardFields = Partial<
  Pick<
    Doc<"cardChecklist">,
    | "teamCheckDoneAt"
    | "teamCheckOutcome"
    | "bscTeamName"
    | "teamNoneConfirmedAt"
    | "teamNoneConfirmedByUserId"
    | "variationOfCardId"
    | "variationParentManual"
  >
>;

/** A card whose content has been decided, ready to become a row. */
export type NewCardRow = {
  selectorOptionId: Id<"selectorOptions">;
  cardNumber: string;
  cardName: string;
  playerIds?: Array<Id<"players">>;
  /** NEO-254 — always written together with `playerIds`, never apart. */
  playerLinks?: Array<{ playerId: Id<"players">; nameOnCard: string }>;
  teamOnCardIds?: Array<Id<"teams">>;
  /**
   * NEO-569 — the card's league when the caller already knows it (a parallel
   * copy carries its source card's, when it carries the source's teams).
   * Absent: derived before the insert from the teams and the set's leagues
   * (`cardLeague.deriveNewCardLeagueId`).
   */
  leagueId?: Id<"leagues">;
  attributes?: string[];
  isRookie?: boolean;
  isRelic?: boolean;
  printRun?: number;
  cardVariation?: string;
  /** Observed only: folded into `features.autographed`, never stored. */
  autographType?: string;
  /** STORED shape — slot keys on `selectorOptionId`, already resolved. */
  platformData: Doc<"cardChecklist">["platformData"];
  /** Already bounded by the caller; omitted from the row when empty. */
  pendingPlayerNames: string[];
  /**
   * NEO-528 round 3 — the listing this card comes from named a player (see
   * schema.ts). Written only when true. The checklist commit sets it through
   * `listingNamesAPlayer`; a parallel copy carries its source's; a
   * hand-added card never passes it.
   */
  listingNamedPlayer?: true;
  pendingTeamNames: string[];
  sortOrder: number;
  /** Canonical player names, for Signed By and the listing text. */
  playerNames: string[];
  /** Canonical team names, for the listing text. */
  teamNames?: string[];
  /**
   * NEO-606 — the Location / Name split of those teams that have one, read
   * off their rows by the caller, so the title can give a team's location up
   * before the team. Absent when none is split.
   */
  teamSplits?: ListingTeamSplit[];
  /**
   * NEO-528 round 3 — the people the card is born with under "Also on this
   * card" (its cameos), with their NB names for the description's cameo
   * line. Usually `bornCardPlayers`' answer. Repeats and the card's own
   * players are left out and the list is cut at `MAX_CARD_PLAYERS`; the
   * stored list and the description always name the same people.
   */
  cameos?: ReadonlyArray<BornCameo>;
  carried?: CarriedCardFields;
  /**
   * NEO-312 — the features map to merge the card's observed facts ONTO,
   * instead of `set.inheritedFeatures`. A parallel copy passes
   * `copyFeaturesForParallel`'s answer here so the insert card's own facts
   * (an autograph, Signed By, a short print) survive the copy. The commit
   * never passes it.
   */
  baseFeatures?: Record<string, string>;
  /**
   * NEO-312 (R2) — the SKU of the old parallel card this copy replaces, when
   * it is clearly the same card. Written as-is instead of generating one.
   */
  keepSku?: string;
  /**
   * NEO-321 (Jason, 2026-10-04) — a parallel copy's `features.parallelName`:
   * the NB name of the parallel row the copy lands on, never a marketplace
   * value. Applied LAST, over the snapshot and over the card's observed
   * `cardVariation` (which keeps its own listing token), so every copy's
   * title names its parallel. The commit never passes it.
   */
  parallelName?: string;
  /**
   * NEO-335 — the operator's own title from the wizard's "Card titles" step,
   * written verbatim instead of the generated one. Already trimmed and held
   * to `LISTING_TITLE_MAX` by the caller (`listingInputs.checkTitleAnswer`).
   * A human authored it, so `listingTitleTruncated` is never written beside
   * it — the same rule `updateCard` applies to an operator title edit. The
   * commit's insert branch passes it, and (NEO-535) the parallel build, for a
   * copy whose builder title fails but whose source's hand edit, re-headed
   * with the parallel's description, fits (`features/carriedTitle`).
   */
  listingTitle?: string;
  /**
   * NEO-335 — the trimmed title the "Card titles" step SHOWED the operator,
   * which they kept. The title is still GENERATED here (the server's names
   * are the truth, not the client's prediction of them). The "auto title was
   * cut short" flag is skipped only when the generated title is exactly this
   * text: then the question it raises was asked and answered before save. A
   * title that came out differently is one nobody saw, so it is flagged as
   * before (security audit, NEO-335). The commit's insert branch passes it,
   * already trimmed and capped (`listingInputs.checkTitleAnswer`), and
   * (NEO-535) the parallel build, with the title it just generated for a copy
   * built from the box that fits with every first name: the box was the
   * operator's answer, so the copy is not flagged cut short.
   */
  listingTitleKept?: string;
};

/** A cameo a new card is born with: the player, and their NB name. */
export type BornCameo = { playerId: Id<"players">; name: string };

/**
 * NEO-528 round 3 — the cameos a new card actually stores, in order: repeats
 * and the card's own players taken out, cut at `MAX_CARD_PLAYERS`. The same
 * filter `bornSecondaryPlayerFields` applies, applied first here so the
 * description names exactly the stored list.
 */
function bornCameoList(
  card: Pick<NewCardRow, "playerIds" | "playerLinks" | "cameos">,
): BornCameo[] {
  const own = primaryPlayerIdsOf(card);
  const seen = new Set<string>();
  const out: BornCameo[] = [];
  for (const cameo of card.cameos ?? []) {
    const key = cameo.playerId as string;
    if (seen.has(key) || own.has(key)) continue;
    seen.add(key);
    out.push(cameo);
    if (out.length === MAX_CARD_PLAYERS) break;
  }
  return out;
}

/**
 * NEO-528 round 3 — "Player on every card": what a NEW card is born with once
 * the defaults of its row (`cardPlayersBulk.effectiveCardPlayerDefaults`) are
 * applied, through the one per-card rule (`planCardPlayerDefaults`):
 *
 *   - a card that names NO player and carries no name waiting for review gets
 *     the default player: `playerIds`, `playerLinks` (printed as the player's
 *     NB name) and `playerNames`, all three naming them, in one answer;
 *   - a card that names anyone, or holds a pending name, keeps what it has
 *     (a marketplace-resolved or typed player always wins);
 *   - cameos: the card's own first (those `cameoName` cannot name are gone
 *     and left off), then each default cameo that is new, never one of the
 *     card's players. A pending name blocks the player, never the cameos.
 *
 * Writes no team, ever (product invariant 8). Pure. `facts` is what the card
 * arrives with; `cameoName` names its own cameos (null = no longer in NB).
 * With no defaults the card is returned as it came.
 */
export function bornCardPlayers(
  facts: CardPlayerFacts,
  own: {
    playerNames: string[];
    cameoName?: (id: Id<"players">) => string | null;
  },
  defaults: Pick<EffectiveCardPlayerDefaults, "playerId" | "cameoIds" | "player" | "cameos"> | null,
): {
  playerIds?: Array<Id<"players">>;
  playerLinks?: Array<{ playerId: Id<"players">; nameOnCard: string }>;
  playerNames: string[];
  cameos: BornCameo[];
  player: DefaultPlayerPlan;
} {
  const defaultNames = new Map<string, string>();
  for (const cameo of defaults?.cameos ?? []) defaultNames.set(cameo._id as string, cameo.name);
  if (defaults?.player) defaultNames.set(defaults.player._id as string, defaults.player.name);
  const plan = planCardPlayerDefaults(facts, {
    playerId: defaults?.player ? defaults.playerId : null,
    cameoIds: defaults?.cameoIds ?? [],
  });
  const cameos: BornCameo[] = [];
  for (const id of plan.cameos.ids) {
    const name = defaultNames.get(id as string) ?? own.cameoName?.(id) ?? null;
    if (name !== null) cameos.push({ playerId: id, name });
  }
  if (plan.player.kind === "fill" && defaults?.player) {
    const { _id, name } = defaults.player;
    return {
      // NEO-254 — the pair, one list, same order.
      playerIds: [_id],
      playerLinks: [{ playerId: _id, nameOnCard: name }],
      playerNames: [name],
      cameos,
      player: plan.player,
    };
  }
  return {
    ...(facts.playerIds !== undefined ? { playerIds: facts.playerIds } : {}),
    ...(facts.playerLinks !== undefined ? { playerLinks: facts.playerLinks } : {}),
    playerNames: own.playerNames,
    cameos,
    player: plan.player,
  };
}

/**
 * NEO-363 — everything a card row is born with except its `sportId`, which
 * `insertCardRow` adds from the caller's `sport()` (or refuses). Typed as the
 * stored row minus that one field, so a required field the build forgets is a
 * type error rather than a schema failure at insert.
 */
export type BuiltCardRowFields = Omit<
  WithoutSystemFields<Doc<"cardChecklist">>,
  "sportId"
>;

export type BuiltCardRow = {
  row: BuiltCardRowFields;
  /** Everything `generateSku` needs except the random suffix. */
  sku: {
    skuCode?: string;
    sportFallbackLabel: string;
    year: string;
    setName: string;
    cardNumber: string;
  };
};

/**
 * The row a new card is inserted as (without its SKU), plus the SKU inputs.
 * Pure: no database, no clock beyond `now`, no randomness.
 */
export function buildCardRowForInsert(
  card: NewCardRow,
  set: CardRowSetContext,
  now: number,
): BuiltCardRow {
  // NEO-71-74: precedence = the leaf node's complete features snapshot
  // (already resolved at that node's own creation time) < card-observed
  // facts. A fact seen on THIS card (e.g. it's a rookie) beats the
  // inherited values.
  //
  // NEO-335: the merge (and the title inputs below) live in
  // `features/listingInputs.ts`, shared with the wizard's pre-save "Card
  // titles" step, so the title it shows and the one written here cannot
  // drift.
  const mergedFeatures = mergeCardFeatures(card, set);
  // NEO-345 — the leaf's autograph format is applied (and stripped from the
  // card) inside `mergeCardFeatures`, so the pre-save title preview and this
  // insert read one answer.
  // A card arriving already-autographed gets the same "just became non-None
  // -> default Signed By from the roster" treatment `setCardFeature` applies
  // for a manual operator edit.
  const wasBlank = (set.inheritedFeatures?.autographed ?? "None") === "None";
  const isNowSet =
    !!mergedFeatures.autographed && mergedFeatures.autographed !== "None";
  const playerNames = card.playerNames;
  if (wasBlank && isNowSet && !mergedFeatures.signedBy && playerNames.length > 0) {
    mergedFeatures.signedBy = playerNames.join(", ");
  }
  const featuresOrUndefined =
    Object.keys(mergedFeatures).length > 0 ? mergedFeatures : undefined;

  // NEO-24/71-74: write-once listing title/description, generated once here
  // at creation time, then freely editable afterward. `previewListingTitle`
  // must be given the same inputs, or a regenerated title disagrees with the
  // one written here.
  // NEO-528 round 3 — the cameos it is born with, exactly as stored: the
  // description names them, and the title names them while it has room (they
  // are the first meaningful thing it gives up, NEO-535's order).
  const cameos = bornCameoList(card);
  const listingInputs = listingInputsForCard(
    card,
    set,
    {
      playerNames,
      teamNames: card.teamNames,
      teamSplits: card.teamSplits,
      cameoNames: cameos.map((c) => c.name),
    },
    mergedFeatures,
  );
  const listingTitle = assessListingTitle(listingInputs);
  // NEO-335 — the operator's answer from the "Card titles" step, when one
  // rode on the card: their own words, or the trimmed title kept. Either way
  // the cut-short question was put before save, so the flag is not written.
  // NEO-535 / NEO-609 — `coreFits` is false when a Tidy Up cut (a whole team,
  // the number, SP, RELIC, a first name, RC, AUTO) is still out, or the title
  // was built from the set's box text. An over-cap title has cut all of those,
  // so it is flagged `listingTitleTruncated` too; `titleOverLimit` (its
  // length) takes precedence when the attention items are read.
  const operatorTitle = card.listingTitle?.trim();
  const flagTruncated =
    !listingTitle.coreFits &&
    !operatorTitle &&
    card.listingTitleKept !== listingTitle.title;

  const carried = card.carried ?? {};
  const row: BuiltCardRowFields = {
    selectorOptionId: card.selectorOptionId,
    cardNumber: card.cardNumber,
    cardName: card.cardName,
    // NEO-26: legacy `team` removed; only teamOnCardIds[] is written.
    playerIds: card.playerIds,
    // NEO-254 — the same list with the printed name attached; see schema.ts.
    // Never written without the ids beside it.
    playerLinks: card.playerLinks,
    teamOnCardIds: card.teamOnCardIds,
    attributes: card.attributes,
    isRookie: card.isRookie,
    isRelic: card.isRelic,
    printRun: card.printRun,
    // NEO-217: `autographType` is NOT written; `features.autographed` is the
    // one truth for "this card is an autograph".
    // NEO-335 — stored trimmed (blank is none), the value the pre-save
    // "Card titles" step measured; see `listingInputs.storedCardVariation`.
    cardVariation: storedCardVariation(card.cardVariation),
    platformData: card.platformData,
    // NEO-528 round 3 — absent when it has none; the field is named only by
    // its one writer (`cardSecondaryPlayers.ts`).
    ...bornSecondaryPlayerFields(card, cameos.map((c) => c.playerId)),
    ...(featuresOrUndefined ? { features: featuresOrUndefined } : {}),
    // NEO-363 — required and never blank: the generated title always carries
    // the description or the card number (NEO-535 cuts the number only from a
    // title that is over the cap without it), and a blank operator answer
    // falls through to it.
    listingTitle: operatorTitle || listingTitle.title,
    listingDescription: generateListingDescription(listingInputs, {
      cameoNames: cameos.map((c) => c.name),
    }),
    // NEO-535 / NEO-609: only in Tidy Up, or when the box text was used
    // (see schema.ts), and NEO-335: never over an operator's pre-save answer.
    ...(flagTruncated ? { listingTitleTruncated: true } : {}),
    // NEO-221 / NEO-246 — omitted entirely when empty, so a fully-reviewed
    // commit writes exactly the row it wrote before these fields existed.
    ...(card.pendingPlayerNames.length
      ? { pendingPlayerNames: card.pendingPlayerNames }
      : {}),
    // NEO-528 round 3 — provenance, only when true (absent on every other
    // card, so their rows are exactly what they were).
    ...(card.listingNamedPlayer === true ? { listingNamedPlayer: true as const } : {}),
    ...(card.pendingTeamNames.length
      ? { pendingTeamNames: card.pendingTeamNames }
      : {}),
    // NEO-312 — a copy's NB-owned rulings, spread only when present so a
    // commit's row is unchanged.
    ...(carried.teamCheckDoneAt !== undefined
      ? { teamCheckDoneAt: carried.teamCheckDoneAt }
      : {}),
    // NEO-345 — why that lookup finished; travels with the stamp it explains.
    ...(carried.teamCheckOutcome !== undefined
      ? { teamCheckOutcome: carried.teamCheckOutcome }
      : {}),
    ...(carried.bscTeamName !== undefined
      ? { bscTeamName: carried.bscTeamName }
      : {}),
    ...(carried.teamNoneConfirmedAt !== undefined
      ? { teamNoneConfirmedAt: carried.teamNoneConfirmedAt }
      : {}),
    ...(carried.teamNoneConfirmedByUserId !== undefined
      ? { teamNoneConfirmedByUserId: carried.teamNoneConfirmedByUserId }
      : {}),
    ...(carried.variationOfCardId !== undefined
      ? { variationOfCardId: carried.variationOfCardId }
      : {}),
    ...(carried.variationParentManual !== undefined
      ? { variationParentManual: carried.variationParentManual }
      : {}),
    sortOrder: card.sortOrder,
    lastUpdated: now,
  };

  return {
    row,
    sku: {
      skuCode: set.sportSkuCode,
      sportFallbackLabel: set.sportValue,
      year: mergedFeatures.season ?? "",
      setName: set.setNameValue ?? "",
      cardNumber: card.cardNumber,
    },
  };
}

/**
 * How a new card's player index is kept (NEO-313). `sport` is the CARD's
 * sport, the root of its selector chain; a caller can cache it across a whole
 * page (the commit chunk's `cardSport`). NEO-358 asks it for every card, to
 * stamp `cardChecklist.sportId`; NEO-363 refuses the insert when it has no
 * answer (`requireCardSport`).
 */
export type CardRowIndexing = {
  sport: () => Promise<Id<"selectorOptions"> | undefined>;
  /**
   * NEO-569 — team and set league reads for the card's `leagueId`, shared
   * across the page. Every production caller passes its page's cache; absent,
   * the insert reads with a cache of its own (same answer, more reads).
   */
  leagueCache?: CardLeagueCache;
};

/**
 * NEO-363 — the refusal when a card's row has no sport above it. The walk
 * (`findSportForSelectorOption`) comes back empty only for a broken chain: an
 * ancestor that no longer exists, or one more than 16 levels deep. Neither is
 * something a card should be saved under, and `cardChecklist.sportId` is
 * required, so the write stops here with a message instead of failing the
 * schema check.
 */
export const NO_CARD_SPORT_REFUSAL =
  "Couldn't find the sport this card's set sits under, so the card wasn't saved.";

/** The card's sport, or the `NO_CARD_SPORT_REFUSAL` error. */
export function requireCardSport(
  sportId: Id<"selectorOptions"> | undefined,
): Id<"selectorOptions"> {
  if (!sportId) throw new ConvexError(NO_CARD_SPORT_REFUSAL);
  return sportId;
}

/**
 * Insert a new card row, keep its derived player index (NEO-313), then patch
 * in its SKU.
 *
 * NEO-91: insert-then-patch, as the commit has always done it. The random
 * suffix (not the id) is what makes the SKU unique; the order is kept so the
 * row a commit writes is exactly the row it wrote before this was shared.
 *
 * NEO-313: every card born through here gets its `cardPlayerLinks` rows in
 * the same transaction, exactly as the commit chunk did inline before this
 * was shared — `fresh: true` (the card was inserted a line ago, so there is
 * nothing to diff against) and only when it carries players. Doing it HERE
 * rather than at each call site is what keeps a second caller (the parallel
 * build) from ever minting an unindexed card; `cardPlayerLinks.pin.test.ts`
 * pins it.
 *
 * NEO-358: and, in the same place for the same reason, the card's `sportId`
 * (set here, once, never changed), its `cardTeamLinks` rows (`fresh: true`,
 * only when it carries teams), and +1 on its row's counts in the caller's
 * `ledger`. The ledger is REQUIRED: the caller flushes it once, last.
 *
 * NEO-363: `sportId` is required on the row, so a card with no sport above it
 * is refused before anything is written (`requireCardSport`).
 */
export async function insertCardRow(
  ctx: MutationCtx,
  card: NewCardRow,
  set: CardRowSetContext,
  indexing: CardRowIndexing,
  ledger: CardCountLedger,
): Promise<Id<"cardChecklist">> {
  const sportId = requireCardSport(await indexing.sport());
  const built = buildCardRowForInsert(card, set, Date.now());
  // The insert below is typed against the schema, so leaving `sportId` (or
  // any required field the build forgot) off this object is a type error.
  // NEO-569 — born with its league, never patched in after the insert.
  const leagueCache = indexing.leagueCache ?? newCardLeagueCache();
  const leagueId =
    card.leagueId ?? (await deriveNewCardLeagueId(ctx, card, leagueCache));
  const row = {
    ...built.row,
    sportId,
    ...(leagueId ? { leagueId } : {}),
    // NEO-312 (R2): a rebuilt card that is clearly the old one keeps its SKU,
    // so a label or a listing that already names it still does.
    ...(card.keepSku ? { sku: card.keepSku } : {}),
  };
  const id: Id<"cardChecklist"> = await ctx.db.insert("cardChecklist", row);
  if ((card.playerIds ?? []).length > 0) {
    await syncCardPlayerLinks(ctx, id, card.playerIds, sportId, {
      fresh: true,
    });
  }
  if ((card.teamOnCardIds ?? []).length > 0) {
    await syncCardTeamLinks(ctx, { _id: id, selectorOptionId: row.selectorOptionId, leagueId }, card.teamOnCardIds, {
      fresh: true,
      leagueCache,
    });
  }
  // NEO-528 round 3 — and its cameo index rows, through the one writer. The
  // names are already known, so the writer reads no player.
  if ((card.cameos ?? []).length > 0) {
    const names = newStoredCardReadCache();
    for (const cameo of card.cameos ?? []) names.players.set(cameo.playerId as string, cameo.name);
    await bornSecondaryPlayers(ctx, id, row, names);
  }
  ledger.addCard(row);
  if (!card.keepSku) {
    await ctx.db.patch(id, {
      sku: generateSku({ ...built.sku, uniqueSuffix: crypto.randomUUID() }),
    });
  }
  return id;
}

/**
 * NEO-312 (hobby A4) — the features a PARALLEL copy of an insert card starts
 * from, before the card's observed facts are applied on top.
 *
 * Three layers, in order:
 *
 *   1. the parallel's own snapshot — the set-level facts of the row the copy
 *      now lives under (`cardType: Parallel`, its release date, …);
 *   2. the insert card's CARD-LEVEL facts — every key whose value on the card
 *      differs from the insert row's snapshot, i.e. a fact observed on that
 *      card or set on it by an operator (an autograph, Signed By, a short
 *      print, a prospect flag). A fact the card merely inherited is not one;
 *      the parallel's own snapshot already speaks for the set level;
 *   3. except on PARALLEL facts, where the parallel's snapshot wins: the keys
 *      in `PARALLEL_FACT_KEYS`, and any key the parallel's snapshot sets to a
 *      different value than the insert's (an operator's parallel-level edit).
 *
 * Pure, and NB data only: both snapshots and the card's features are NB rows.
 */
export const PARALLEL_FACT_KEYS: ReadonlySet<string> = new Set([
  // What the parallel IS. There is no colour or print-run feature key today
  // (`expectedFeatures.ts`); when one is added it belongs in this set.
  "parallelName",
  "cardType",
]);

export function copyFeaturesForParallel(args: {
  insertSnapshot: Record<string, string> | undefined;
  parallelSnapshot: Record<string, string> | undefined;
  insertCardFeatures: Record<string, string> | undefined;
}): Record<string, string> {
  const insertSnapshot = args.insertSnapshot ?? {};
  const parallelSnapshot = args.parallelSnapshot ?? {};
  const out: Record<string, string> = { ...parallelSnapshot };
  const parallelOwns = (key: string): boolean =>
    key in parallelSnapshot &&
    (PARALLEL_FACT_KEYS.has(key) || parallelSnapshot[key] !== insertSnapshot[key]);
  for (const [key, value] of Object.entries(args.insertCardFeatures ?? {})) {
    if (value === insertSnapshot[key]) continue; // inherited, not a card fact
    if (parallelOwns(key)) continue;
    out[key] = value;
  }
  return out;
}
